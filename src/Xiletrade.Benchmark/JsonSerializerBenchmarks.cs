using BenchmarkDotNet.Attributes;
using BenchmarkDotNet.Order;
using System;
using System.IO;
using System.Text;
using Xiletrade.Library.Models.Application.Serialization;
using Xiletrade.Library.Models.Poe.Contract;
using Xiletrade.Library.Services;

namespace Xiletrade.Benchmark;

/// <summary>
/// This benchmark compares serialization between System.Text.Json (as used by Xiletrade : UTF-8 only, source generation)
/// and Utf8Json 1.3.7 released in 2018.
/// </summary>
/// <remarks>
/// Compare biggest JSON file used by Xiletrade. 
/// Interning : loading of the data files by DataManagerService (strings shared through a StringCache).
/// NoReplace : serialization without the replacements done for the trade api (SerializeToUtf8Bytes directly).
/// </remarks>
[MemoryDiagnoser]
//[NativeMemoryProfiler]
[Orderer(SummaryOrderPolicy.FastestToSlowest)]
[RankColumn]
public class JsonSerializerBenchmarks
{
    public static byte[] Json { get; private set; }
    public static FilterData Filter { get; private set; }
    public static IJsonSerializer Utf8Serializer { get; private set; } = new Utf8JsonSerializer();
    public static JsonHelper NETSerializer { get; private set; } = new();

    [GlobalSetup]
    public void Setup()
    {
        LoadFile();
        // object to serialize : read with the serializer of the application (source generation)
        Filter = NETSerializer.Deserialize<FilterData>(Json);
    }

    /// <summary>
    /// Reads the file from the data copied with the library next to the executable (as DataManagerService does) :
    /// the current directory is not reliable, the benchmarks run in a process generated by BenchmarkDotNet.
    /// </summary>
    public static void LoadFile()
    {
        string path = Path.Combine(DataManagerService.DataDirectory, "Lang", "fr-FR", "Filters.json"); // es,fr,br,jp
        if (!File.Exists(path))
        {
            throw new FileNotFoundException("Filter file not found next to the benchmark", path);
        }

        Json = File.ReadAllBytes(path);
        if (Json.AsSpan().StartsWith(Encoding.UTF8.Preamble))
        {
            Json = Json[Encoding.UTF8.Preamble.Length..];
        }
    }

    /// <summary>
    /// deprecated
    /// </summary>
    [Benchmark]
    public void DeserializeWithUtf8()
    {
        Utf8Serializer.Deserialize<FilterData>(Json);
    }

    [Benchmark]
    public void DeserializeWithNET()
    {
        NETSerializer.Deserialize<FilterData>(Json);
    }

    // as DataManagerService loads the data files
    [Benchmark]
    public void DeserializeWithNETInterning()
    {
        NETSerializer.Deserialize<FilterData>(Json, context: NETSerializer.CreateInterningContext(new StringCache()));
    }

    /// <summary>
    /// deprecated
    /// </summary>
    [Benchmark]
    public void SerializeWithUtf8()
    {
        Utf8Serializer.Serialize<FilterData>(Filter);
    }

    // as Xiletrade serializes (trade queries, configuration)
    [Benchmark]
    public void SerializeWithNET()
    {
        NETSerializer.SerializeToUtf8<FilterData>(Filter);
    }

    [Benchmark]
    public void SerializeWithNETNoReplace()
    {
        NETSerializer.SerializeToUtf8<FilterData>(Filter, replace: false);
    }
}
